function downArrowShapes(
  x: number,
  yTop: number,
  yBottom: number,
  strokeWidth = 2,
): SvgShape[] {
  const tipY = yBottom - 2;
  const headBaseY = yBottom - 10;
  return [
    {
      kind: 'line',
      x1: x,
      y1: yTop,
      x2: x,
      y2: headBaseY,
      stroke: 'currentColor',
      strokeWidth,
    },
    {
      kind: 'polygon',
      points: `${x - 4},${headBaseY} ${x + 4},${headBaseY} ${x},${tipY}`,
      fill: 'currentColor',
      stroke: 'none',
    },
  ];
}

